import { Tex, TexBlock } from "@/components/admin/docs/math";
import { Code, Note, Prose } from "@/components/admin/docs/prose";

export default function WatermarkCalibration() {
  return (
    <Prose>
      <p>
        Чтобы снимать знак формулой, нужна его карта прозрачности <Tex>{String.raw`\alpha(x, y)`}</Tex> для каждого из четырёх
        размеров и цвет <Tex>W</Tex>. Поставщик их не публикует, поэтому они восстановлены по его же фото: на одном снимке знак
        лежит поверх неизвестного товара, но сотни снимков вместе выдают его точную форму.
      </p>

      <h2 id="idea">Идея: белый фон</h2>
      <p>
        Если под точкой знака гладкий светлый фон <Tex>B</Tex>, то из <Tex>{String.raw`J = \alpha W + (1-\alpha) B`}</Tex>{" "}
        прозрачность выражается напрямую:
      </p>
      <TexBlock>{String.raw`\alpha = \frac{B - J}{B - W} .`}</TexBlock>
      <p>
        Чем больше <Tex>{String.raw`B - W`}</Tex>, тем точнее оценка: ошибка в <Tex>J</Tex> на один уровень (шум JPEG) даёт
        ошибку <Tex>{String.raw`1/(B-W)`}</Tex> в <Tex>\alpha</Tex>. Идеален чисто белый фон, где{" "}
        <Tex>{String.raw`B - W \approx 224`}</Tex>. Фото товаров на белом у поставщика большинство, поэтому данных хватает.
      </p>

      <h2 id="steps">Как считается</h2>
      <ol>
        <li>
          Каждое фото прогоняется через детектор с текущими шаблонами. Нужно знать размер знака и его положение с точностью до
          пикселя. Знак всегда по центру, поэтому совмещение точное, без интерполяции.
        </li>
        <li>
          Фон <Tex>B</Tex> под штрихами восстанавливается по окружающим пикселям без знака. Точка используется, только если фон
          вокруг ровный (разброс не больше 3 уровней) и светлый (<Tex>{String.raw`B > 170`}</Tex>).
        </li>
        <li>
          Берутся только фото с обычным серым знаком в один слой (подобранный цвет в пределах ±8 от <Tex>W</Tex>), иначе тёмные
          и двойные знаки исказят форму.
        </li>
        <li>
          Для каждой точки шаблона оценки <Tex>{String.raw`\alpha_i`}</Tex> с разных фото объединяются взвешенным средним в два
          прохода. Вес — квадрат «контраста» относительно белого фона, так что чисто белый фон весит 1:
        </li>
      </ol>
      <TexBlock>{String.raw`w_i = \left( \frac{B_i - W}{255 - W} \right)^2, \qquad \bar\alpha = \frac{\sum_i w_i\, \alpha_i}{\sum_i w_i}, \qquad s^2 = \frac{\sum_i w_i (\alpha_i - \bar\alpha)^2}{\sum_i w_i} .`}</TexBlock>
      <p>
        Во втором проходе среднее считается заново только по оценкам, которые ближе к первому среднему чем{" "}
        <Tex>{String.raw`2{,}5\,s`}</Tex>. Так отсекаются фото, где в точку попал край товара или блик:
      </p>
      <TexBlock>{String.raw`\hat\alpha = \frac{\sum_{i:\, |\alpha_i - \bar\alpha| \le 2{,}5 s} w_i\, \alpha_i}{\sum_{i:\, |\alpha_i - \bar\alpha| \le 2{,}5 s} w_i} .`}</TexBlock>
      <p>
        Точка обновляется, только если набралось хотя бы три «белых эквивалента» (<Tex>{String.raw`\sum w_i \ge 3`}</Tex>), иначе
        остаётся прежнее значение. Вариант знака пересчитывается, если для него нашлось хотя бы 20 подходящих фото.
      </p>
      <Note title="Калибровка уточняет, а не ищет с нуля">
        Фото отбираются текущими шаблонами: детектор должен найти знак, а подобранный цвет должен быть обычным серым. Поэтому
        калибровка исправляет шаблон, который уже примерно верен. Так было с размытым малым шаблоном: со старым шаблоном отбор
        прошли 104 фото из 155. Если поставщик сменит логотип целиком, понадобится новый стартовый шаблон.
      </Note>
      <Note title="Почему нельзя просто взять один шаблон и уменьшить">
        Пробовали: большой шаблон, уменьшенный до размера малого любым фильтром (area, linear, cubic, Lanczos), совпадает хуже,
        чем откалиброванный по фото. Малый знак у поставщика отрисован отдельно, и края его штрихов устроены иначе.
      </Note>

      <h2 id="results">Что дала перекалибровка</h2>
      <p>
        Малый шаблон изначально был оценён всего по 37 фото и получился размытым. После перекалибровки по 104 фото средняя
        ошибка снятия на малых знаках упала с 6,9 до 3,7 уровня — столько же, сколько у большого и среднего (3,2–3,4: это уже
        уровень шума JPEG). Крошечный шаблон пока построен по 18 фото, его стоит перекалибровать на данных из прода.
      </p>

      <h2 id="how">Как перекалибровать</h2>
      <p>На сервере, когда в базе накопятся фото:</p>
      <ol>
        <li>
          <code>docker compose exec worker python -m app.cli watermark-sample /tmp/wm 3000</code> — скачать 3000 случайных
          оригиналов;
        </li>
        <li>
          <code>docker compose exec worker python -m app.cli watermark-calibrate /tmp/wm</code> — пересчитать шаблоны (пишутся
          на volume с фото и подхватываются после перезапуска);
        </li>
        <li>
          <code>docker compose restart api worker</code>;
        </li>
        <li>
          переобработать фото нужного варианта: кнопка в <a href="/admin/settings">настройках</a> или{" "}
          <code>python -m app.cli requeue-images small</code>. Старые версии остаются на сайте, пока не готовы новые.
        </li>
      </ol>

      <Code files={["backend/app/images/calibrate.py", "backend/app/images/data/itp_watermark.npz"]} />
    </Prose>
  );
}
